#!/usr/bin/env node
/* gen-ubl-samples.mjs — bundle the two sample invoices into the page.
 *
 * The checker runs entirely in the visitor's tab and the page says so, so the
 * samples must not be fetched either: a "0 network requests" counter next to a
 * GET for the sample would be a lie by omission. They are inlined from the same
 * files that `node validate.mjs` is run against, so what the page checks is what
 * was verified on disk. Runs in prebuild; also `npm run gen:ubl`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.join(here, "..");
const read = (n) => readFileSync(path.join(site, "public/ubl", n), "utf8");

const out = `/* GENERATED by scripts/gen-ubl-samples.mjs — do not edit.
   Source: public/ubl/sample-valid.xml · public/ubl/sample-broken.xml
   Both are fictional businesses; the valid one passes \`node validate.mjs\` with
   zero errors and the broken one fails it with four. */
export const SAMPLE_VALID = ${JSON.stringify(read("sample-valid.xml"))};
export const SAMPLE_BROKEN = ${JSON.stringify(read("sample-broken.xml"))};
`;
writeFileSync(path.join(site, "content/ubl-samples.ts"), out);
console.log("gen:ubl — content/ubl-samples.ts written");
